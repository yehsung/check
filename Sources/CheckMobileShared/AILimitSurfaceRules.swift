import Foundation

// MARK: - 리밋 표면 규칙(폰·위젯이 **한 벌로** 쓰는 문턱 · 불투명도) — v0.3.45
//
// 왜 이 파일이 `CheckMobileShared` 에 있는가: 리밋을 그리는 두 프로세스(폰 앱 `CheckMobileKit` ·
// 위젯 확장 `CheckWidgetsKit`)가 **서로를 링크하지 않는다**(Package.swift — 위젯은 앱 모듈을 보지 못한다).
// 둘이 공통으로 보는 모듈은 여기뿐이고, 표시 규칙의 숫자를 모듈마다 적으면 한쪽만 고쳐지는 날
// 같은 데이터가 두 화면에서 다르게 보인다(이 기능이 몇 번이고 밟은 함정 — '세 화면이 다른 말을 하는 자리').
//
// 값·캡션·표시여부 자체는 `CheckCore` 의 `AILimitFreshnessRule` 이 만든다. 여기 있는 것은 그 규칙이
// **알 수 없는 것** 셋뿐이다:
//  · 유령 행 문턱 — 서버에 남은 행을 '그 제공자를 더는 안 쓴다'로 볼 나이(코어 규칙은 한 창의 참/거짓만 안다).
//  · 하한 채움 불투명도 — 바를 가진 화면만 쓰는 그리기 값.
//  · 그릴 줄이 **하나도 없을 때의 한 문장**(v0.3.47) — 코어 규칙은 창 하나만 보고 '아무것도 없는 화면'을 모른다.

/// 서버에 남아 **영원히 늙는** 행을 목록에서 가리는 문턱. 폰과 위젯이 같은 값을 쓴다.
///
/// ## 왜 필요한가 (2026-10-07 실증)
/// 맥에서 어떤 제공자를 로그아웃하면 그 제공자는 업로드에서 **빠질 뿐**이다. 서버에는 DELETE 권한도 정리
/// cron 도 없어 그 행이 남고, 시간이 지나면 리셋 시각을 지나 `0% · 초기화됨` 으로 **굳는다** — 쓰지도 않는
/// 도구가 "한도를 하나도 안 썼다"로 영구 표시된다(가장 비싼 방향의 거짓: 사용자가 그 숫자를 보고 계획을 세운다).
///
/// ## 왜 위젯도 **자기 시각으로 다시** 재야 하는가
/// 폰은 서버 응답을 받는 순간 이 문턱을 적용한다. 그런데 위젯이 읽는 패널은 **앱이 열릴 때만** 다시 써지고,
/// 위젯은 그 파일을 몇 시간·며칠 뒤의 칸 시각으로 그린다(리밋 위젯은 지평 밖 칸까지 깐다 —
/// `AingWidgetLimitsTimelinePlan`). 그래서 "쓸 때는 안 유령이었지만 그릴 때는 유령"인 창이 열린다.
/// 판정을 **그리는 시각**에서 다시 해야 그 창이 닫힌다.
public enum AILimitGhostRow {
    /// 이보다 오래된 `observedAt` 은 유령이다(3일).
    ///
    /// 값의 근거: 맥이 켜져 있으면 10분마다 올라오므로 산 제공자는 몇 분을 안 넘는다. 3일은 그 사이에 들어갈
    /// 수 있는 가장 긴 정상 공백(주말 내내 맥을 끈 사람)보다 **짧지 않게**, 그러나 "쓰지 않게 된 도구"를
    /// 영원히 들고 있지 않을 만큼은 **짧게** 잡은 값이다. 어느 쪽으로 틀려도 손해가 비대칭이 아니다
    /// (숨겨도 맥을 켜면 10분 안에 돌아오고, 남겨도 나이 캡션이 "3일 전"으로 말한다).
    public static let maxObservationAge: TimeInterval = 3 * 86_400

    /// 이 관측을 가릴 것인가. **미래 시각은 여기서 가리지 않는다** — 기기 시계가 어긋난 경우이고 그 판정은
    /// 코어 규칙이 한다(유예를 넘는 미래 관측은 `unknown`). 여기서 재는 것은 '너무 오래됐나' 하나다.
    public static func isGhost(observedAt: Date, now: Date) -> Bool {
        now.timeIntervalSince(observedAt) >= maxObservationAge
    }
}

/// 하한("27% 이상")인 값의 바 채움을 **흐리게** 그리는 값. 맥 `AILimitBar` 와 같은 뜻이고 같은 수다.
///
/// 왜 흐리게인가: 같은 길이의 바가 등호(`27%`)와 하한(`27% 이상`)에서 똑같이 보이면, 글자의 "이상"만
/// 읽지 못한 사람에게 **바가 거짓말을 한다**("지금 27% 다"로 읽는다).
///
/// ★ 왜 색이 아니라 불투명도인가: 위젯 틴트·투명 모드는 색을 통째로 버리고 **알파만 남긴다**
/// (`AingWidgetInk` 머리말). 하한을 다른 색으로 말하면 그 모드에서 신호가 사라진다.
public enum AILimitFloorFill {
    /// 하한일 때의 채움 불투명도.
    public static let floorOpacity: Double = 0.55

    /// 채움 불투명도(하한이면 흐리게, 등호면 1).
    public static func opacity(floorOnly: Bool) -> Double {
        floorOnly ? floorOpacity : 1
    }
}

/// 그릴 줄이 **하나도 없을 때** 폰 카드와 위젯이 쓰는 한 문장. 두 모듈이 **같은 상수**를 쓴다
/// (각자 적으면 한쪽만 고쳐지는 날 같은 상태를 두 화면이 다르게 말한다 — 이 파일이 있는 이유).
///
/// ## 왜 "로그인하면 보여요" 를 버렸나 (v0.3.47)
/// 0.3.46 까지 이 자리의 문장은 "맥 앱에서 AI 도구에 로그인하면 보여요" 였다. 그때는 **설정 토글이 없었으므로**
/// 줄이 하나도 없는 까닭이 '연동이 없다' 하나뿐이었다. v0.3.47 이 맥 설정에 보기 스위치를 두면서 까닭이 둘이 됐고,
/// **끈 사람에게 그 문장은 거짓**이다 — 그 사람은 이미 로그인해 있고, 몇 번을 더 로그인해도 카드는 비어 있다.
/// (끄면 맥이 그 제공자의 행을 **값 전부 null 로 덮어** 올리고, 폰·위젯은 보이는 창이 0개인 행을 숨긴다.)
///
/// ## 왜 두 경우를 가려 다르게 말하지 않나 — 이 한 문장으로 고른 근거 넷
/// ① **위젯은 가릴 수 없다.** 위젯이 읽는 패널(`WidgetSnapshot.AILimitPanel`)에는 비워진 행이 애초에 실리지
///    않는다(폰이 넘기기 전에 거른다). 가리게 하려면 새 칸을 하나 더 실어야 하고, 위젯 확장은 앱과 **따로**
///    갱신되므로 한동안은 그 칸이 없는 파일·없는 코드가 섞인다 → 그 표면에는 **결국 두 경우에 다 맞는 문장이
///    필요하다**. 그렇다면 둘로 늘릴 이유가 없다.
/// ② **폰의 단서는 스스로 사라진다.** 폰은 비워진 행을 볼 수 있지만(그 행은 `bundle.providers` 에 창 0개로
///    남는다) 그 행도 3일이면 유령 문턱을 지나 사라진다 → 사용자가 아무것도 하지 않았는데 **문구가 혼자 바뀐다**.
/// ③ **다음 행동이 같은 자리다.** 두 경우 모두 사용자가 손댈 곳은 맥이고(폰에는 이 스위치가 없다), 한 문장이
///    그 두 문을 같이 가리킬 수 있다.
/// ④ 세 화면이 같은 상태를 다르게 말하는 것이 이 기능이 몇 번이고 밟은 함정이다.
public enum AILimitSurfaceText {
    /// 보이는 제공자가 0명일 때의 한 줄. **두 문을 순서대로** 가리킨다(연동 → 보기 설정) —
    /// 둘 중 어느 쪽이 닫혀 있어도 참이고, 어느 쪽이 닫혔는지 몰라도 할 일이 적혀 있다.
    public static let noVisibleProviders = "맥 앱에서 AI 도구에 로그인하고 리밋 보기를 켜면 보여요"

    /// 고른 맥 대신 **다른 맥**을 그리고 있을 때의 한 줄(v0.3.47 P1).
    ///
    /// ## 왜 이름을 적는 것만으로는 부족한가 — 한 줄을 더 두기로 한 근거
    /// 머리글에 그리는 맥의 이름을 적으면 "이 숫자는 이 맥 것"은 참이 된다. 그런데 사용자가 맥 설정에서 고른
    /// 맥은 **다른 맥**이고, 그 사실을 아는 유일한 단서가 "머리글의 이름이 내가 고른 이름과 다르다"뿐이면
    /// 자연스러운 결론은 **"고르기가 저장되지 않았다"** 다(사용자가 다시 고르러 간다 — 고쳐질 것이 없는데).
    /// 그래서 대체가 일어났다는 사실을 글자로 말한다. 맥 설정 쪽을 손대라는 뜻도 함께 들어 있다.
    ///
    /// ## 왜 **고른 맥의 이름을 적지 않나**
    /// 적을 수 있는 값이 있긴 하다(폰은 숨긴 맥까지 든 명부를 쥐고 있다). 그런데 그 이름의 겹침 꼬리는
    /// **보이는 묶음들 사이에서만** 갈려 있어서(`displayGroups` 가 그 규약이다 — 숨은 맥까지 세면 화면에 하나뿐인
    /// `Mac mini` 에 쓸데없는 꼬리가 붙는다), 숨은 맥의 이름을 그 집합 밖에서 적으면 "이름은 같은데 꼬리는
    /// 한쪽에만 있는" 조합이 생긴다 — 이름을 가르려고 만든 장치가 **가를 수 없는 짝**을 만드는 꼴이다.
    /// 이름 없이도 이 문장이 할 일(고르기는 살아 있고, 지금 숫자는 다른 맥 것이다)은 전부 전달된다.
    ///
    /// ## 왜 까닭(유령 / 전부 껐음)을 가르지 않나
    /// 이 파일의 `noVisibleProviders` 와 **같은 근거**다(§왜 두 경우를 가려 다르게 말하지 않나): 3일이 지나면
    /// 비워진 행도 유령 문턱을 지나 사라져 **사용자가 아무것도 하지 않았는데 문구가 혼자 바뀐다**.
    /// 그리고 두 경우의 다음 행동이 같은 자리(맥)다.
    public static let substitutedMainDevice = "고른 맥은 지금 보여 줄 숫자가 없어서 다른 맥을 보여 주고 있어요"
}
